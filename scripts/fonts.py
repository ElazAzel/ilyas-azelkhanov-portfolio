"""Build site fonts from brand/fonts-src: subset, pin extra axes, write woff2 + @font-face CSS.

Run: pnpm fonts  (needs: pip install fonttools brotli)
"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "brand" / "fonts-src"
OUT = ROOT / "public" / "fonts"
TS = ROOT / "app" / "font-faces.ts"

# Latin + Russian + Kazakh + typographic punctuation + ₸ and №.
KAZAKH = "ӘәҒғҚқҢңӨөҰұҮүҺһІі"
UNICODES = (
    list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + list(range(0x400, 0x460))
    + [ord(c) for c in KAZAKH]
    + list(range(0x2010, 0x2027))
    + [0x2030, 0x2039, 0x203A, 0x20B8, 0x2116, 0x2122, 0x2212, 0x2190, 0x2191, 0x2192, 0x2193]
)
FEATURES = ["kern", "liga", "calt", "tnum", "lnum", "case", "ccmp", "locl", "mark", "mkmk"]

# Fallback sizing: width of SAMPLE in em, measured once in Arial (Liberation Sans has identical advances).
SAMPLE = "Сделаю сайт, бота или AI-процесс — и научу команду с ним работать. Azelkhanov 0123456789"
ARIAL_EM = {"regular": 44.2212, "bold": 46.7729}


def subset_font(src):
    font = TTFont(SRC / src, lazy=False)
    opts = subset.Options()
    opts.layout_features = FEATURES
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=UNICODES)
    sub.subset(font)
    missing = [c for c in KAZAKH if ord(c) not in font.getBestCmap()]
    assert not missing, f"{src}: missing Kazakh glyphs {missing}"
    return font


def sample_em(font):
    cmap, hmtx, upm = font.getBestCmap(), font["hmtx"], font["head"].unitsPerEm
    return sum(hmtx[cmap[ord(c)]][0] for c in SAMPLE) / upm


def fallback_face(name, font, weight, arial_key, locals_):
    upm, hhea = font["head"].unitsPerEm, font["hhea"]
    size = sample_em(font) / ARIAL_EM[arial_key]
    src = ", ".join(f'local("{n}")' for n in locals_)
    return (
        f'@font-face {{\n  font-family: "{name}";\n  src: {src};\n  font-weight: {weight};\n'
        f"  ascent-override: {hhea.ascent / upm / size * 100:.2f}%;\n"
        f"  descent-override: {abs(hhea.descent) / upm / size * 100:.2f}%;\n"
        f"  line-gap-override: {hhea.lineGap / upm / size * 100:.2f}%;\n"
        f"  size-adjust: {size * 100:.2f}%;\n}}"
    )


def face(family, file, weights):
    return (
        f'@font-face {{\n  font-family: "{family}";\n  src: url("/fonts/{file}") format("woff2");\n'
        f"  font-weight: {weights};\n  font-style: normal;\n  font-display: swap;\n}}"
    )


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    css = ["/* Generated by scripts/fonts.py — do not edit by hand. */"]

    geo = subset_font("geologica.ttf")
    geo_reg = instancer.instantiateVariableFont(geo, {"wght": 400, "CRSV": 0, "SHRP": 0, "slnt": 0})
    geo = subset_font("geologica.ttf")
    geo_bold = instancer.instantiateVariableFont(geo, {"wght": 760, "CRSV": 0, "SHRP": 0, "slnt": 0})
    geo = subset_font("geologica.ttf")
    geo = instancer.instantiateVariableFont(geo, {"wght": (300, 800), "CRSV": 0, "SHRP": 0, "slnt": 0})
    geo.flavor = "woff2"
    geo.save(OUT / "geologica.woff2")
    css.append(face("Geologica", "geologica.woff2", "300 800"))
    css.append(fallback_face("Geologica Fallback", geo_reg, "300 599", "regular",
                             ["Arial", "ArialMT", "Helvetica Neue", "Liberation Sans"]))
    css.append(fallback_face("Geologica Fallback", geo_bold, "600 800", "bold",
                             ["Arial Bold", "Arial-BoldMT", "Helvetica Neue Bold", "Liberation Sans Bold"]))

    fira = subset_font("firacode.ttf")
    fira = instancer.instantiateVariableFont(fira, {"wght": (300, 700)})
    fira.flavor = "woff2"
    fira.save(OUT / "firacode.woff2")
    css.append(face("Fira Code", "firacode.woff2", "300 700"))

    body = "\n\n".join(css[1:]).replace("`", "\\`")
    TS.write_text(
        "// Generated by scripts/fonts.py — do not edit by hand.\n"
        "// Inlined in app/layout.tsx so font URLs can carry the deploy base path.\n"
        f"export const FONT_FACES = `{body}`;\n"
    )
    for f in sorted(OUT.glob("*.woff2")):
        print(f"{f.name}: {f.stat().st_size / 1024:.1f} KB")


if __name__ == "__main__":
    main()
