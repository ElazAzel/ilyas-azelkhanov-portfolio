// Generates app/tokens.css and content/tokens.json from the YAML front matter of DESIGN.md.
// DESIGN.md is the only source of design tokens. Run: pnpm tokens
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { parse } from "yaml";

const md = readFileSync(new URL("../DESIGN.md", import.meta.url), "utf8");
const front = md.match(/^---\n([\s\S]*?)\n---/);
if (!front) throw new Error("DESIGN.md has no front matter");
const t = parse(front[1]);

const MIN_VW = 375;
const MAX_VW = 1440;
const FALLBACK = {
  Geologica: '"Geologica", "Geologica Fallback", system-ui, sans-serif',
  "Fira Code": '"Fira Code", ui-monospace, "Courier New", monospace',
};

const rem = (v) => {
  const n = parseFloat(v);
  if (String(v).endsWith("rem")) return n;
  if (String(v).endsWith("px")) return n / 16;
  throw new Error(`Unsupported size ${v}`);
};
const r4 = (n) => Math.round(n * 10000) / 10000;

// Fluid size between X-mobile (at 375px) and X (at 1440px).
function fluid(min, max) {
  const a = rem(min);
  const b = rem(max);
  const slope = (b - a) / ((MAX_VW - MIN_VW) / 16); // rem per rem of viewport
  const intercept = a - slope * (MIN_VW / 16);
  return `clamp(${a}rem, ${r4(intercept)}rem + ${r4(slope * 100)}vw, ${b}rem)`;
}

const lines = [];
lines.push("/* Generated by scripts/tokens.mjs from DESIGN.md - do not edit by hand. */");
lines.push("@theme {");
// Only tokens from DESIGN.md exist: Tailwind's default palettes and scales are switched off.
for (const ns of ["color", "font", "text", "radius", "spacing", "font-weight", "tracking", "leading", "shadow", "breakpoint"]) {
  lines.push(`  --${ns}-*: initial;`);
}
lines.push("  --spacing: initial;");
lines.push("  --breakpoint-md: 48rem;");
lines.push("  --breakpoint-lg: 64rem;");
lines.push("  --breakpoint-xl: 90rem;");
for (const [k, v] of Object.entries(t.colors)) lines.push(`  --color-${k}: ${v};`);
lines.push("  --color-transparent: transparent;");
lines.push("  --color-current: currentColor;");
lines.push(`  --font-sans: ${FALLBACK.Geologica};`);
lines.push(`  --font-mono: ${FALLBACK["Fira Code"]};`);
for (const [k, v] of Object.entries(t.rounded)) lines.push(`  --radius-${k}: ${v};`);
for (const [k, v] of Object.entries(t.spacing)) lines.push(`  --spacing-${k}: ${v};`);
lines.push("  --spacing-0: 0px;");
lines.push("  --spacing-px: 1px;");
lines.push("}");
lines.push("");

// Typography: one utility per token; tokens with a -mobile pair become fluid.
for (const [name, s] of Object.entries(t.typography)) {
  if (name.endsWith("-mobile")) continue;
  const mobile = t.typography[`${name}-mobile`];
  const size = mobile ? fluid(mobile.fontSize, s.fontSize) : s.fontSize;
  const body = [
    `font-family: ${FALLBACK[s.fontFamily] ?? s.fontFamily};`,
    `font-size: ${size};`,
    `font-weight: ${s.fontWeight};`,
    `line-height: ${(mobile ?? s).lineHeight};`,
  ];
  const tracking = (mobile ?? s).letterSpacing;
  if (tracking) body.push(`letter-spacing: ${tracking};`);
  if (s.fontFeature) body.push(`font-feature-settings: ${s.fontFeature};`);
  if (mobile) {
    const wide = [`line-height: ${s.lineHeight};`];
    if (s.letterSpacing) wide.push(`letter-spacing: ${s.letterSpacing};`);
    body.push(`@media (width >= 64rem) {\n    ${wide.join("\n    ")}\n  }`);
  }
  lines.push(`@utility t-${name} {\n  ${body.join("\n  ")}\n}`);
}

writeFileSync(new URL("../app/tokens.css", import.meta.url), lines.join("\n") + "\n");
mkdirSync(new URL("../content/", import.meta.url), { recursive: true });
writeFileSync(
  new URL("../content/tokens.json", import.meta.url),
  JSON.stringify({ colors: t.colors, typography: t.typography, rounded: t.rounded, spacing: t.spacing }, null, 2) + "\n",
);
console.log("tokens: app/tokens.css, content/tokens.json");
